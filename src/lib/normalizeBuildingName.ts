// 건물명 정규화 유틸
//
// 관리자가 건물을 등록/수정할 때와, 앞으로 만들 PDF Import의 건물 자동매칭 기능이
// "같은 건물인지" 비교할 때 반드시 동일한 규칙을 써야 합니다. 그래서 이 함수 하나로
// 통일해두고, 두 곳(관리자 화면 저장 로직 / 나중의 Import 매칭 로직)이 똑같이 가져다 씁니다.
//
// 하는 일: 공백 제거, 대소문자 통일(영문만 영향), 괄호/하이픈 등 특수문자 제거.
// 하지 않는 일: 한글↔영문 변환, 약어 확장(예: "타워"→"Tower") 같은 임의 변환은 하지 않습니다.
// (그런 변환은 오히려 다른 건물을 같은 건물로 잘못 묶는 위험이 있습니다.)
export function normalizeBuildingName(name: string | null | undefined): string {
  if (!name) return "";
  return name
    .trim()
    .toLowerCase()
    .replace(/\s+/g, "")
    // 유니코드 "문자(L)"와 "숫자(N)" 카테고리만 남기고 나머지(공백/특수문자/괄호/하이픈 등)는 제거
    .replace(/[^\p{L}\p{N}]/gu, "");
}
